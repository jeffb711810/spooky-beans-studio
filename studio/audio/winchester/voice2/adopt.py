# Make the conformed Aiden take THE narration: back up Adam, install Aiden in ../voice, regenerate the film's captions
# (RicksClips chunking, voice at frame 36) and the per-frame lip-sync envelope (VENV).
import json, re, os, shutil, wave, numpy as np
V = "../voice/"; SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "src", "videos", "bellwitch") + "/"; FPS, OFF, NF = 30, 36, 2370
# (Adam is gone: ../voice/timeline_target.json keeps only the cut timing the film was built on)
shutil.copy("voice_tight.wav", V + "voice_tight.wav"); shutil.copy("words.json", V + "words.json")
W = json.load(open(V + "words.json"))
words = []
for x in W:
    disp = x["w"].split("~")[0]
    if "~" in x["w"] and words and words[-1]["raw"] == disp and words[-1]["tilde"]: words[-1]["e"] = x["e"]; continue
    words.append({"t": disp, "s": x["s"], "e": x["e"], "raw": disp, "tilde": "~" in x["w"]})
TINY = {"a", "an", "the", "of", "to", "in", "on", "by", "at", "i"}
chunks, cur = [], []
for i, w in enumerate(words):
    cur.append(w); nxt = words[i + 1] if i + 1 < len(words) else None
    punct = bool(re.search(r"[,.!?;:…]$", w["t"])); gap = (nxt["s"] - w["e"]) if nxt else 9
    lone_small = len(cur) == 1 and w["t"].lower().strip(",.") in TINY and not (nxt and nxt["t"].lower().strip(",.") in TINY)
    if punct or gap > 0.28 or nxt is None or len(cur) >= 2 or not lone_small: chunks.append(cur); cur = []
out = []
for k, c in enumerate(chunks):
    a = round(c[0]["s"] * FPS) + OFF; end_hold = round((c[-1]["e"] + 0.35) * FPS) + OFF
    b = round(chunks[k + 1][0]["s"] * FPS) + OFF if k + 1 < len(chunks) else end_hold
    b = min(b, max(end_hold, a + 8)); out.append({"t": " ".join(w["t"] for w in c), "a": a, "b": max(b, a + 6)})
with open(SRC + "captions.ts", "w") as f:
    f.write("// WINCHESTER captions (generated by stories/winchester/voice2/adopt.py from voice/words.json = Aiden, voice starts at frame 36)\n")
    f.write("export const CAPTIONS: { t: string; a: number; b: number }[] = [\n")
    for o in out: f.write(f"  {{ t: {json.dumps(o['t'])}, a: {o['a']}, b: {o['b']} }},\n")
    f.write("];\n")
w = wave.open(V + "voice_tight.wav", "rb"); sr = w.getframerate(); x = np.frombuffer(w.readframes(w.getnframes()), np.int16).astype(np.float32) / 32768; w.close()
hop = sr // FPS; env = np.zeros(NF)
for f in range(NF):
    k = (f - OFF) * hop
    if 0 <= k < len(x): env[f] = np.sqrt(np.mean(x[k:k + hop] ** 2) + 1e-12)
db = 20 * np.log10(env + 1e-9); top = np.percentile(db[env > 1e-4], 97)
v = np.clip((db - (top - 34)) / 31, 0, 1)
sm = v.copy()
for f in range(1, NF): sm[f] = max(v[f], sm[f - 1] * 0.55)      # fast open, quick close (no mush between syllables)
with open(SRC + "voiceEnv.ts", "w") as f:
    f.write("// per-frame voice loudness 0..1 (lip sync), frame 0 = video start (voice offset 36 f); Aiden take\n")
    f.write("export const VENV = [" + ",".join(f"{q:.2f}" for q in sm) + "];\n")
print(len(out), "caption chunks;", "VENV mean", round(float(sm.mean()), 3), "first chunks", [o["t"] for o in out[:8]])
